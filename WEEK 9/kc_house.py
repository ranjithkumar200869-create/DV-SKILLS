import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("kc_house_data.csv")

print("First 5 Rows:")
print(df.head())

print("\nDataset Shape:")
print(df.shape)

print("\nDataset Information:")
df.info()

print("\nMissing Values:")
print(df.isnull().sum())

df["bedrooms"] = df["bedrooms"].replace(0, np.nan)
df["bathrooms"] = df["bathrooms"].replace(0, np.nan)

df["bedrooms"] = df["bedrooms"].fillna(
    df["bedrooms"].median()
)
df["bathrooms"] = df["bathrooms"].fillna(
    df["bathrooms"].median()
)

for col in df.select_dtypes(include=np.number).columns:
    df[col] = df[col].fillna(df[col].median())

df = df.drop_duplicates()

df["date"] = pd.to_datetime(
    df["date"], errors="coerce"
)

df = df.dropna(subset=["date"])

df["sale_year"] = df["date"].dt.year
df["sale_month"] = df["date"].dt.month

df["years_since_renovation"] = np.nan

renovated = df["yr_renovated"] > 0

df.loc[renovated, "years_since_renovation"] = (
    df.loc[renovated, "sale_year"]
    - df.loc[renovated, "yr_renovated"]
)

df.loc[
    df["years_since_renovation"] < 0,
    "years_since_renovation"
] = np.nan

print("\nFinal Dataset Shape:")
print(df.shape)

print("\nMissing Values After Cleaning:")
print(df.isnull().sum())

# Save Cleaned Data
df.to_csv("cleaned_kc_house_data.csv", index=False)

print("\nCleaned dataset saved successfully!")